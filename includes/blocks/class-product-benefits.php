<?php
/**
 * Product Benefits block registration and conditional asset loading.
 *
 * The block is fully static (saved markup, no PHP render callback). This class
 * registers it from block.json and makes sure its frontend stylesheet is only
 * printed on requests where the block is actually rendered.
 *
 * @package WBD_Product_Benefits_Blocks
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Product Benefits block module.
 */
final class WBD_Product_Benefits_Blocks_Product_Benefits {

	/**
	 * Block name.
	 *
	 * @var string
	 */
	const NAME = 'wbd/product-benefits';

	/**
	 * Build folder name.
	 *
	 * @var string
	 */
	const DIR = 'product-benefits';

	/**
	 * Registers the block type and related hooks.
	 */
	public static function register() {
		$path = WBD_Product_Benefits_Blocks::get_block_build_path( self::DIR );

		if ( ! file_exists( $path . '/block.json' ) ) {
			return;
		}

		$block_type = register_block_type( $path );

		if ( ! $block_type ) {
			return;
		}

		if ( ! empty( $block_type->editor_script_handles ) ) {
			foreach ( $block_type->editor_script_handles as $handle ) {
				wp_set_script_translations( $handle, 'wbd-product-benefits-blocks', WBD_PRODUCT_BENEFITS_BLOCKS_PATH . 'languages' );
			}
		}

		add_action( 'wp_enqueue_scripts', array( __CLASS__, 'maybe_dequeue_style' ), 100 );
		add_filter( 'render_block_' . self::NAME, array( __CLASS__, 'enqueue_style_on_render' ), 10, 1 );
	}

	/**
	 * Frontend style handle generated by WordPress from block.json.
	 *
	 * @return string
	 */
	private static function get_style_handle() {
		return generate_block_asset_handle( self::NAME, 'style' );
	}

	/**
	 * Classic themes enqueue every registered block stylesheet on every page.
	 * Remove ours when the current singular content does not contain the block.
	 * enqueue_style_on_render() restores it if the block appears elsewhere
	 * (widgets, template parts, synced patterns, archive loops).
	 */
	public static function maybe_dequeue_style() {
		if ( is_admin() || wp_should_load_separate_core_block_assets() ) {
			return;
		}

		if ( is_singular() && has_block( self::NAME, get_queried_object_id() ) ) {
			return;
		}

		wp_dequeue_style( self::get_style_handle() );
	}

	/**
	 * Ensures the stylesheet is enqueued when the block renders.
	 *
	 * @param string $block_content Rendered block markup.
	 * @return string
	 */
	public static function enqueue_style_on_render( $block_content ) {
		$handle = self::get_style_handle();

		if ( ! wp_style_is( $handle, 'enqueued' ) && ! wp_style_is( $handle, 'done' ) ) {
			wp_enqueue_style( $handle );
		}

		return $block_content;
	}
}
